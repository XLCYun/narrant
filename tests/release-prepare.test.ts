import { execFileSync, spawnSync } from "node:child_process";
import {
  cpSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { resolve } from "node:path";
import { afterEach, describe, expect, it } from "vitest";

const repositoryRoot = resolve(import.meta.dirname, "..");
const releaseScript = resolve(repositoryRoot, "scripts/release-prepare.mjs");
const releaseVersionCheckScript = resolve(
  repositoryRoot,
  "scripts/release-version-check.mjs",
);
const temporaryRepositories: string[] = [];

/** 创建包含全部版本声明的最小 Git 仓库，用于从公开 CLI 验证发布准备行为。 */
function createReleaseRepository(): string {
  const repository = mkdtempSync(resolve(tmpdir(), "narrant-release-prepare-"));
  temporaryRepositories.push(repository);

  writeFileSync(
    resolve(repository, "package.json"),
    `${JSON.stringify({ name: "narrant", version: "1.1.0" }, null, 2)}\n`,
  );
  writeFileSync(
    resolve(repository, "src-tauri-tauri.conf.json"),
    `${JSON.stringify({ productName: "Narrant", version: "1.1.0" }, null, 2)}\n`,
  );
  mkdirSync(resolve(repository, "src-tauri"));
  mkdirSync(resolve(repository, "src-tauri/src"));
  cpSync(
    resolve(repository, "src-tauri-tauri.conf.json"),
    resolve(repository, "src-tauri/tauri.conf.json"),
  );
  rmSync(resolve(repository, "src-tauri-tauri.conf.json"));
  writeFileSync(
    resolve(repository, "src-tauri/Cargo.toml"),
    '[package]\nname = "narrant"\nversion = "1.1.0"\nedition = "2021"\n',
  );
  writeFileSync(
    resolve(repository, "src-tauri/Cargo.lock"),
    '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "narrant"\nversion = "1.1.0"\n',
  );
  writeFileSync(resolve(repository, "src-tauri/src/lib.rs"), "pub fn release_fixture() {}\n");

  execFileSync("git", ["init", "--initial-branch=main"], { cwd: repository });
  execFileSync("git", ["config", "user.name", "Release Test"], { cwd: repository });
  execFileSync("git", ["config", "user.email", "release@example.com"], {
    cwd: repository,
  });
  execFileSync("git", ["add", "."], { cwd: repository });
  execFileSync("git", ["commit", "-m", "initial"], { cwd: repository });
  execFileSync("git", ["tag", "-a", "v1.1.0", "-m", "v1.1.0"], {
    cwd: repository,
  });
  return repository;
}

/** 读取发布准备脚本维护的四份版本声明。 */
function readVersions(repository: string): string[] {
  const packageJson = JSON.parse(readFileSync(resolve(repository, "package.json"), "utf8"));
  const tauriConfig = JSON.parse(
    readFileSync(resolve(repository, "src-tauri/tauri.conf.json"), "utf8"),
  );
  const cargoManifest = readFileSync(resolve(repository, "src-tauri/Cargo.toml"), "utf8");
  const cargoLock = readFileSync(resolve(repository, "src-tauri/Cargo.lock"), "utf8");
  return [
    packageJson.version,
    tauriConfig.version,
    cargoManifest.match(/\[package]\s+[\s\S]*?version = "([^"]+)"/)?.[1],
    cargoLock.match(/\[\[package\]\]\s+name = "narrant"\s+version = "([^"]+)"/)?.[1],
  ];
}

afterEach(() => {
  for (const repository of temporaryRepositories.splice(0)) {
    rmSync(repository, { recursive: true, force: true });
  }
});

describe("release preparation CLI", () => {
  it("updates every version declaration and creates one release commit with an annotated tag", () => {
    const repository = createReleaseRepository();

    const result = spawnSync("node", [releaseScript, "1.2.0"], {
      cwd: repository,
      encoding: "utf8",
    });

    expect(result.stderr).toBe("");
    expect(result.status).toBe(0);
    expect(readVersions(repository)).toEqual(["1.2.0", "1.2.0", "1.2.0", "1.2.0"]);
    expect(
      execFileSync("git", ["log", "-1", "--pretty=%s"], {
        cwd: repository,
        encoding: "utf8",
      }).trim(),
    ).toBe("chore(release): v1.2.0");
    expect(
      execFileSync("git", ["cat-file", "-t", "refs/tags/v1.2.0"], {
        cwd: repository,
        encoding: "utf8",
      }).trim(),
    ).toBe("tag");
    expect(
      execFileSync("node", [releaseVersionCheckScript, "v1.2.0"], {
        cwd: repository,
        encoding: "utf8",
      }).trim(),
    ).toBe("1.2.0");
  });

  it("rejects inconsistent current versions without changing the repository", () => {
    const repository = createReleaseRepository();
    const tauriConfigPath = resolve(repository, "src-tauri/tauri.conf.json");
    writeFileSync(
      tauriConfigPath,
      readFileSync(tauriConfigPath, "utf8").replace('"1.1.0"', '"1.0.0"'),
    );
    execFileSync("git", ["add", "."], { cwd: repository });
    execFileSync("git", ["commit", "-m", "create inconsistent fixture"], {
      cwd: repository,
    });
    const headBefore = execFileSync("git", ["rev-parse", "HEAD"], {
      cwd: repository,
      encoding: "utf8",
    });

    const result = spawnSync("node", [releaseScript, "1.2.0"], {
      cwd: repository,
      encoding: "utf8",
    });

    expect(result.status).toBe(1);
    expect(result.stderr).toContain("当前版本声明不一致");
    expect(execFileSync("git", ["rev-parse", "HEAD"], { cwd: repository, encoding: "utf8" })).toBe(
      headBefore,
    );
    expect(spawnSync("git", ["rev-parse", "--verify", "refs/tags/v1.2.0"], { cwd: repository }).status).not.toBe(0);
  });

  it("rejects a version that does not advance the latest stable tag", () => {
    const repository = createReleaseRepository();
    execFileSync("git", ["tag", "-a", "v2.0.0", "-m", "v2.0.0"], {
      cwd: repository,
    });

    const result = spawnSync("node", [releaseScript, "1.2.0"], {
      cwd: repository,
      encoding: "utf8",
    });

    expect(result.status).toBe(1);
    expect(result.stderr).toContain("必须高于最新稳定标签 v2.0.0");
    expect(readVersions(repository)).toEqual(["1.1.0", "1.1.0", "1.1.0", "1.1.0"]);
  });

  it("restores files and the branch when annotated tag creation fails after committing", () => {
    const repository = createReleaseRepository();
    const headBefore = execFileSync("git", ["rev-parse", "HEAD"], {
      cwd: repository,
      encoding: "utf8",
    });
    execFileSync("git", ["config", "tag.gpgSign", "true"], { cwd: repository });
    execFileSync("git", ["config", "gpg.program", "/usr/bin/false"], { cwd: repository });

    const result = spawnSync("node", [releaseScript, "1.2.0"], {
      cwd: repository,
      encoding: "utf8",
    });

    expect(result.status).toBe(1);
    expect(execFileSync("git", ["rev-parse", "HEAD"], { cwd: repository, encoding: "utf8" })).toBe(
      headBefore,
    );
    expect(readVersions(repository)).toEqual(["1.1.0", "1.1.0", "1.1.0", "1.1.0"]);
    expect(execFileSync("git", ["status", "--porcelain"], { cwd: repository, encoding: "utf8" })).toBe(
      "",
    );
  });
});
